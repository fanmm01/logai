# ============================================================
#  加载角色到 CombatEngine
# ============================================================

def load_character_to_engine(engine, char_data: dict, user_id: str):
    """Load a character definition into the CombatEngine."""
    char = engine.get_char(user_id)
    char.name = char_data['name']
    char.serial = char_data.get('serial', '')
    for k, v in char_data.get('attrs', {}).items():
        char.set_attr(k, v)
    for k, v in char_data.get('str_attrs', {}).items():
        char.set_str(k, v)
    # Initial phase (for cartridge-based characters like 麦知夏)
    init_phase = char_data.get('initial_phase', 0)
    if init_phase:
        char.phase = init_phase

    # Load summon templates referenced by this character's spells
    summon_names = set()
    for spell in char_data.get('spells', []):
        for eff in spell.get('effects', []):
            tmpl = eff.get('召唤物模板', '')
            if tmpl and tmpl in SUMMON_TEMPLATES:
                summon_names.add(tmpl)
    for ti, tmpl_name in enumerate(sorted(summon_names), 1):
        tmpl = SUMMON_TEMPLATES[tmpl_name]
        prefix = f"召唤物模板{CN_NUMS[ti]}"
        char.set_str(f"{prefix}名称", tmpl_name)
        for k in ['HP','MP','SAN','STR','CON','SIZ','DEX','APP','INT','POW','EDU',
                  '闪避','MOV','额外行动数','可反击','可反应','可格挡','格挡',
                  'max_simultaneous', 'max_total_spawned']:
            if k in tmpl and tmpl[k] is not None:
                char.set_attr(f"{prefix}{k}", tmpl[k])
        for si, sk in enumerate(tmpl.get('skills', []), 1):
            char.set_str(f"{prefix}技能{si}", sk)

    for si, spell in enumerate(char_data.get('spells', []), 1):
        prefix = f"技能{CN_NUMS[si]}"
        char.set_str(f"{prefix}名称", spell['name'])
        char.set_str(f"{prefix}时机", spell.get('timing', '2'))
        char.set_attr(f"{prefix}类别", spell.get('category', 1))
        # MP cost: could be int or dice string
        mp_val = spell.get('消耗mp', 0)
        if isinstance(mp_val, str):
            char.set_str(f"{prefix}消耗mp", mp_val)
        else:
            char.set_attr(f"{prefix}消耗mp", mp_val)
        # SAN cost: could be int or dice string
        san_val = spell.get('消耗san', 0)
        if isinstance(san_val, str):
            char.set_str(f"{prefix}消耗san", san_val)
        else:
            char.set_attr(f"{prefix}消耗san", san_val)
        char.set_attr(f"{prefix}默认延续性", spell.get('default_persist', 0))
        char.set_attr(f"{prefix}吟唱回合", spell.get('吟唱回合', 0))
        # Phase (0=universal, 1=phase1, 2=phase2)
        char.set_attr(f"{prefix}阶段", spell.get('phase', 0))
        # MP formula
        mpf = spell.get('_mp_formula', '')
        if mpf: char.set_str(f"{prefix}_mp_formula", mpf)
        # Extended fields for new mechanics
        wr = spell.get('weapon_required', '')
        if wr: char.set_str(f"{prefix}weapon_required", wr)
        cr = spell.get('counter_required')
        if cr: char.set_str(f"{prefix}counter_required", json.dumps(cr))
        cct = spell.get('cost_counter_type', '')
        if cct: char.set_str(f"{prefix}cost_counter_type", cct)
        cca = spell.get('cost_counter_amount', 0)
        if cca: char.set_attr(f"{prefix}cost_counter_amount", cca)
        ob = spell.get('_once_per_battle', False)
        if ob: char.set_attr(f"{prefix}_once_per_battle", 1)
        for ei, eff in enumerate(spell.get('effects', [])):
            letter = CAT_LETTERS[ei]
            prefix_l = f"{prefix}类别{letter}"
            for k, v in eff.items():
                if k == 'type':
                    if v > 8:  # Store non-standard types (9=hpTrigger, 10=delayedHeal, 11=battleSpirit)
                        char.set_attr(f"{prefix_l}type", v)
                    continue
                if isinstance(v, bool):
                    char.set_attr(f"{prefix_l}{k}", 1 if v else 0)
                elif isinstance(v, int):
                    char.set_attr(f"{prefix_l}{k}", v)
                elif isinstance(v, float):
                    char.set_attr(f"{prefix_l}{k}", v)
                elif isinstance(v, (list, dict)):
                    # Serialize complex types to JSON string
                    char.set_str(f"{prefix_l}{k}", json.dumps(v, ensure_ascii=False))
                elif isinstance(v, str):
                    char.set_str(f"{prefix_l}{k}", v)
    # Initialize default weapon (must be before load_spells for weapon_required filtering)
    if char_data.get('serial') == 'Y16':
        char.set_str('_weapon_name', 'staff')
    engine.load_spells(user_id)
    # Load inventory items (物品栏)
    for inv_entry in char_data.get('inventory', []):
        item_name = inv_entry.get('item', '')
        count = inv_entry.get('count', 1)
        if item_name and count > 0:
            engine.add_item_to_inventory(user_id, item_name, count)
    # Handle pre-transformed characters (变身前：——)
    if char_data.get('pre_transformed'):
        char.hs_transformed = True
        char.combat_active = True
        engine._init_combat_hp(user_id, char.get_attr('体力', 10))
    return char
